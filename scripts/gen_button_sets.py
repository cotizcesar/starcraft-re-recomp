#!/usr/bin/env python3
"""Generate `engine-rust/fixtures/button_sets.in` from your own menu-time dump.

Usage: gen_button_sets.py DUMP [OUT]

DUMP is a read-only memory snapshot of the 32-bit StarCraft 1.23.10 client
at the main menu, saved as a PE image (the project calls it
`research/work/sc_mem_menu_pe.exe`; see `research/tools/` for the capture
tooling).  The unit-indexed button-set array lives at file offset 0xb2ddf8:
`{u32 count, u32 buttons_va, u32 ?}` per unit; each button is the 20-byte
record `{u16 pos, u16 icon, u32 cond, u32 act, u16 cond_var, u16 act_var,
u16 enabled_string, u16 disabled_string}` (VA = offset + 0x400000).

The output is Blizzard data, so it is gitignored; `src/button_sets.rs`
includes it at build time (via `build.rs`, which substitutes an empty table
when it is absent).
"""
import struct
import sys
from pathlib import Path

ARRAY = 0xB2DDF8
BASE = 0x400000


def read_sets(dump: bytes) -> dict[int, list[tuple]]:
    sets: dict[int, list[tuple]] = {}
    for uid in range(250):
        count, ptr, _ = struct.unpack_from("<III", dump, ARRAY + uid * 12)
        if count > 40:
            break
        if count and BASE <= ptr < BASE + len(dump):
            off = ptr - BASE
            sets[uid] = [struct.unpack_from("<HHIIHHHH", dump, off + k * 20) for k in range(count)]
        else:
            sets[uid] = []
    return sets


def render(sets: dict[int, list[tuple]]) -> str:
    """The `&[...]` array expression `src/button_sets.rs` includes."""
    lines = ["// Generated by scripts/gen_button_sets.py; Blizzard data, gitignored.", "&["]
    for uid in range(max(sets) + 1):
        bs = sets.get(uid, [])
        if not bs:
            lines.append("    &[],")
            continue
        lines.append("    &[")
        for pos, icon, cf, af, cv, av, es, ds in bs:
            lines.append(f"        b({pos}, {icon}, 0x{cf:x}, 0x{af:x}, {cv}, {av}, {es}, {ds}),")
        lines.append("    ],")
    lines.append("]")
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    dump = Path(sys.argv[1]).read_bytes()
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else (
        Path(__file__).resolve().parents[1] / "engine-rust/fixtures/button_sets.in"
    )
    sets = read_sets(dump)
    out.write_text(render(sets))
    print(f"wrote {out}: {sum(1 for v in sets.values() if v)} unit button sets")


if __name__ == "__main__":
    main()
