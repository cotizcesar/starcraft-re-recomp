#!/usr/bin/env python3
"""Proof sheets for the Options, campaign and in-game 1:1 goals.

For every reference it renders the raw engine frame (no calibration layer)
with the gate phases of `ui_visual_diff.py`, and writes
`<out>/<group>-<id>-<screen>.png`: retail | sc_view | |diff| x4, all
cropped to the 2560x1440 content box.  `<out>/REPORT.md` lists the mean
absolute difference and the share of pixels off by more than 30.

Live retail captures (driven with a uinput mouse, 2026-11-02) are read from
`<out>/live-*.png`; they are copyrighted output of the user's own client, so
the folder stays local (`*.png` is gitignored).

Usage: make_proof_sheets.py --install "$SC_INSTALL" [--out DIR]
"""
import argparse
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import ui_visual_diff as U  # noqa: E402

REFS = ROOT / "engine-rust/docs/original_screenshots"
OPTIONS = ["130933", "130938", "130942", "130949", "130954"]
CAMPAIGN = ["130744", "130750", "130757", "130804", "130824", "130832", "130840", "131132"]
INGAME = ["134905", "134919", "134931", "135020", "135051", "135109", "135114", "135121"]
# live capture file -> (sc_view shot screen, what it shows)
LIVE = {
    "live-mission-list-top.png": ("mission-live", "list opened: entry 0 selected, top of list"),
    "live-mission-list-scrolled.png": ("mission-live-scrolled", "row 2 clicked, down arrow once"),
    "live-locked-zerg-prompt.png": ("episode-locked-zerg", "locked Zerg clicked: strRACE_ERR_ZERG"),
}


def content(img: Image.Image) -> Image.Image:
    img = img.convert("RGB")
    return img.crop((440, 0, 3000, 1440)) if img.width == 3440 else img


def sheet(ref: Image.Image, ours: Image.Image, title: str, out: Path) -> tuple[float, float]:
    a = np.asarray(ref).astype(np.int16)
    b = np.asarray(ours).astype(np.int16)
    d = np.abs(a - b)
    mean = float(d.mean())
    over = float((d.max(axis=2) > 30).mean() * 100)
    diff = Image.fromarray(np.clip(d * 4, 0, 255).astype(np.uint8))
    w, h = 1280, 720
    canvas = Image.new("RGB", (w * 3 + 20, h + 44), (40, 40, 40))
    for i, (img, label) in enumerate(
        [(ref, "retail"), (ours, "sc_view (raw, no calibration)"), (diff, "|diff| x4")]
    ):
        canvas.paste(img.resize((w, h), Image.LANCZOS), (i * (w + 10), 44))
        ImageDraw.Draw(canvas).text((i * (w + 10) + 6, 26), label, fill=(255, 255, 0))
    ImageDraw.Draw(canvas).text(
        (6, 6), f"{title}   mean |diff| {mean:.2f}   >30: {over:.2f}%", fill=(255, 255, 255)
    )
    canvas.save(out)
    return mean, over


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--install", required=True)
    ap.add_argument("--out", default=str(ROOT / "engine-rust/docs/new_screenshots"))
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    with tempfile.TemporaryDirectory(prefix="gc-proof-") as tmp:
        for group, ids in (("options", OPTIONS), ("campaign", CAMPAIGN), ("ingame", INGAME)):
            for rid in ids:
                screen = U.SCREENS[rid]
                bmp = Path(tmp) / f"{rid}.bmp"
                U.render(screen, args.install, bmp)
                ref = content(Image.open(next(REFS.glob(f"Screenshot_*{rid}.png"))))
                name = f"{group}-{rid}-{screen}.png"
                m, o = sheet(ref, Image.open(bmp).convert("RGB"), f"{rid} {screen}", out / name)
                rows.append((group, rid, screen, m, o, name))
                print(f"{group:8} {rid} {screen:34} mean {m:5.2f}  >30 {o:5.2f}%", flush=True)
        for live, (screen, what) in LIVE.items():
            src = out / live
            if not src.is_file():
                print(f"skip {live}: capture not present", flush=True)
                continue
            bmp = Path(tmp) / f"{screen}.bmp"
            U.render(screen, args.install, bmp)
            name = f"proof-{live}"
            m, o = sheet(content(Image.open(src)), Image.open(bmp).convert("RGB"),
                         f"{live} vs {screen} ({what})", out / name)
            rows.append(("live", live.removesuffix(".png"), screen, m, o, name))
            print(f"live     {live:32} {screen:24} mean {m:5.2f}  >30 {o:5.2f}%", flush=True)
    lines = [
        "# Proof sheets (retail | sc_view raw | |diff| x4)",
        "",
        "Generated by `scripts/make_proof_sheets.py`; frames are the raw engine",
        "(no `.gcal` correction layer), clip phases from `ui_visual_diff.py`.",
        "Live captures: the user's retail client driven with a uinput mouse.",
        "",
        "| group | reference | sc_view screen | mean abs diff | px > 30 | sheet |",
        "|---|---|---|---|---|---|",
    ]
    for group, rid, screen, m, o, name in rows:
        lines.append(f"| {group} | {rid} | `{screen}` | {m:.2f} | {o:.2f}% | `{name}` |")
    (out / "REPORT.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(rows)} sheets + REPORT.md to {out}")


if __name__ == "__main__":
    main()
